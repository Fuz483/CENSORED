export function translate(text: string, language: Language): string {
  if (language === "ru") return text;
  if (translations[text]) return translations[text];
  return text;
}

const LanguageContext = createContext<{ language: Language; setLanguage: (language: Language) => void } | null>(null);

export function LanguageProvider({ value, children }: { value: { language: Language; setLanguage: (language: Language) => void }; children: ReactNode }) {
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return { ...context, t: (text: string) => translate(text, context.language) };
}

